def tr(language: str, key: str) -> str:
    return TEXT.get(language, TEXT["Русский"]).get(key, key)


def reliability_label(language: str, score: int, high: int, moderate: int) -> str:
    if score >= high:
        return tr(language, "high")
    if score >= moderate:
        return tr(language, "moderate")
    return tr(language, "limited")
